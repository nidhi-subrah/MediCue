"""Shift summary (feature A): a fixed-structure handoff note per patient for the incoming shift.

The backend computes every fact: requests and confirmations in the window, tap speed against the
patient's own baseline, inconsistent answers, access-mode changes, trend flags and the profile (as the
quotes from the notes behind it, in the care team's words).
A fixed rule sets each patient's status (attention / watch / stable). Gemini only writes the one-line
headline and the "watch for" sentence from those facts; without Gemini a template headline is used and
"watch for" is left out. Numbers are never generated by the model.
"""
from collections import Counter
from datetime import datetime, timedelta, timezone

from ..catalog import Catalog
from ..data.patients import PATIENTS
from .gemini import Gemini

TAP_SLOW_RATIO = 1.5   # tap speed this many times the baseline counts as "slower than usual"


def _status(f: dict) -> str:
    if f["open_urgent"] or any(t["severity"] == "attention" for t in f["trends"]):
        return "attention"
    slow = f["tap_seconds"] and f["baseline_seconds"] and f["tap_seconds"] >= TAP_SLOW_RATIO * f["baseline_seconds"]
    if f["trends"] or f["mode_changes"] or f["inconsistent_answers"] >= 1 or slow:
        return "watch"
    return "stable"


def _template_headline(f: dict) -> str:
    if f["open_urgent"]:
        return f"{f['open_urgent']} urgent request{'s' if f['open_urgent'] > 1 else ''} still open."
    if f["trends"]:
        return f"{f['trends'][0]['label']}: above their usual level."
    if f["inconsistent_answers"] >= 1:
        return "Answers became inconsistent this shift; may be tiring."
    if f["mode_changes"]:
        return "Changed access mode this shift."
    return "Steady this shift."


async def build_handoff(cat: Catalog, store, svc, profiles, gemini: Gemini, trends: list[dict],
                        hours: int = 12) -> dict:
    now = datetime.now(timezone.utc)
    since = now - timedelta(hours=hours)
    flags = {t["patient_id"]: t["flags"] for t in trends}
    mode_changes = await store.mode_changes(hours)

    facts = []
    for p in PATIENTS:
        pid = p["id"]
        rows = await store.confirmations(since, pid)
        live = [a for a in svc.alerts.values()
                if a["patient_id"] == pid and datetime.fromisoformat(a["created_at"]) >= since]
        confirmed = Counter(cat.by_id[r["confirmed_need"]]["label"] for r in rows)
        intervals = [r["mean_tap_interval"] for r in rows if r["mean_tap_interval"] > 0]
        baseline = await store.tap_baseline(pid)
        inconsistent = sum(s.dialogue.inconsistencies for s in svc.sessions.values()
                           if s.patient["id"] == pid and s.started >= since.timestamp())
        f = {
            "patient_id": pid, "name": p["name"], "room": p["room"],
            "requests": len(rows) + sum(a["status"] == "open" for a in live),
            "urgent": sum(bool(r["escalated"]) for r in rows) + sum(
                a["status"] == "open" and a["priority"] == "urgent" for a in live),
            "open_urgent": sum(a["status"] == "open" and a["priority"] == "urgent" for a in live),
            "confirmed": [{"label": k, "count": v} for k, v in confirmed.most_common(4)],
            "tap_seconds": round(sum(intervals) / len(intervals), 1) if intervals else None,
            "baseline_seconds": round(baseline, 1) if baseline else None,
            "inconsistent_answers": inconsistent,
            "mode_changes": mode_changes.get(pid, 0),
            "trends": [{"label": t["label"], "message": t["message"], "severity": t["severity"]}
                       for t in flags.get(pid, [])],
            # The care team's own words (quotes behind the profile), not engine multipliers.
            "profile": list(dict.fromkeys(i["evidence"] for i in profiles.public(pid)["items"]))[:4],
        }
        f["status"] = _status(f)
        f["headline"], f["watch_for"] = _template_headline(f), None
        facts.append(f)

    source = "template"
    notable = [f for f in facts if f["status"] != "stable"]
    if notable and gemini.enabled:
        lines = await gemini.handoff_lines([{k: v for k, v in f.items() if k not in ("headline", "watch_for")}
                                            for f in notable])
        if lines:
            source = "gemini"
            for f in notable:
                if f["patient_id"] in lines:
                    f["headline"] = lines[f["patient_id"]]["headline"]
                    f["watch_for"] = lines[f["patient_id"]]["watch_for"] or None

    order = {"attention": 0, "watch": 1, "stable": 2}
    notable.sort(key=lambda f: (order[f["status"]], f["room"]))
    return {"generated_at": now.isoformat(), "window_hours": hours, "source": source, "patients": notable,
            "stable": [{"patient_id": f["patient_id"], "name": f["name"], "room": f["room"]}
                       for f in facts if f["status"] == "stable"]}
