from datetime import datetime
from typing import Protocol

# Metrics produced per patient per 24 h window (days_ago = 0 is the last 24 h, aligned to now).
SIGNAL_METRICS = ("needs", "pain_needs", "high_risk", "escalations", "avg_taps", "avg_tap_interval",
                  "accuracy", "scan_share")


class Store(Protocol):
    async def init(self) -> None: ...
    async def close(self) -> None: ...
    async def is_empty(self) -> bool: ...
    async def bulk_seed(self, confirmations: list[dict], events: list[dict]) -> None: ...

    async def log_event(self, time: datetime, patient_id: str, session_id: str | None, event_type: str,
                        payload: dict) -> None: ...
    async def log_belief(self, time: datetime, patient_id: str, session_id: str, step: int,
                         belief: dict[str, float]) -> None: ...
    async def log_confirmation(self, row: dict) -> None: ...

    async def window_signals(self, days: int = 8) -> list[dict]: ...
    async def mode_changes(self, hours: int = 24) -> dict[str, int]: ...
    async def confirmations(self, since: datetime, patient_id: str | None = None) -> list[dict]: ...
    async def history_counts(self, patient_id: str) -> dict[str, int]: ...

    async def get_reliability(self, key: str) -> tuple[float, float] | None: ...
    async def set_reliability(self, key: str, a: float, b: float) -> None: ...

    async def events_of_type(self, event_type: str, since: datetime, patient_id: str | None = None) -> list[dict]: ...

    async def list_hypotheses(self) -> list[dict]: ...
    async def upsert_hypothesis(self, hypothesis: dict) -> None: ...
    async def list_inquiries(self) -> list[dict]: ...
    async def upsert_inquiry(self, inquiry: dict) -> None: ...

    # Patient profiles (engine/profile.py) and nurse-note suggestions
    async def tap_baseline(self, patient_id: str, days: int = 14) -> float | None: ...
    async def get_profile(self, patient_id: str) -> dict | None: ...
    async def put_profile(self, profile: dict) -> None: ...
    async def list_suggestions(self) -> list[dict]: ...
    async def upsert_suggestion(self, suggestion: dict) -> None: ...

    # Clinician copilot case records (services/case_packet.py); id = alert id
    async def upsert_case(self, case: dict) -> None: ...
    async def get_case(self, case_id: str) -> dict | None: ...
